import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const plistParser = require('@expo/plist').default;
const { exp } = require('expo/config').getConfig(process.cwd());
assert.equal(exp.ios.bundleIdentifier, 'com.kosaai.salatiq.ioslocal');
assert.equal(exp.name, 'صلاتك');
assert.equal(exp.ios.supportsTablet, false);
assert.deepEqual(exp.ios.entitlements, {});
const modelRoot = 'modules/local-classification/ios/Resources';
const manifest = JSON.parse(fs.readFileSync(`${modelRoot}/best.mlpackage/Manifest.json`, 'utf8'));
assert(manifest.rootModelIdentifier);
const modelItem = manifest.itemInfoEntries[manifest.rootModelIdentifier];
assert(fs.statSync(`${modelRoot}/best.mlpackage/Data/${modelItem.path}`).size > 0);
const contract = JSON.parse(fs.readFileSync(`${modelRoot}/model-contract.json`, 'utf8'));
assert.deepEqual(contract.class_order, ['bowing', 'prostrating', 'sitting', 'standing']);
assert.deepEqual(contract.input.shape, [1, 3, 224, 224]);
assert.deepEqual(contract.output.shape, [1, 4]);
const camera = fs.readFileSync('modules/local-classification/ios/LocalClassificationView.swift', 'utf8');
assert.match(camera, /position: \.front/);
assert.doesNotMatch(camera, /position: \.back|setFacing|URLSession|https?:\/\//);
assert.match(camera, /videoOrientation = \.portrait/);
assert.match(camera, /connection\.isVideoMirrored = false/);
assert.match(camera, /connection\.isVideoMirrored = true/);
assert.match(camera, /alwaysDiscardsLateVideoFrames = true/);
const root = 'ios';
const appFolder = fs.readdirSync(root).find((name) => fs.existsSync(path.join(root, name, 'Info.plist')));
assert(appFolder, 'Generated iOS app folder missing');
const plist = plistParser.parse(fs.readFileSync(path.join(root, appFolder, 'Info.plist'), 'utf8'));
assert.equal(plist.CFBundleDisplayName, 'صلاتك');
assert(plist.NSCameraUsageDescription.includes('الأمامية'));
assert(!plist.NSMicrophoneUsageDescription);
assert(!plist.UIBackgroundModes);
assert.deepEqual(plist.UISupportedInterfaceOrientations, ['UIInterfaceOrientationPortrait']);
const entitlementsFile = fs.readdirSync(path.join(root, appFolder)).find((name) => name.endsWith('.entitlements'));
assert.deepEqual(Object.keys(plistParser.parse(fs.readFileSync(path.join(root, appFolder, entitlementsFile), 'utf8'))), []);
const pbx = fs.readFileSync(path.join(root, `${appFolder}.xcodeproj/project.pbxproj`), 'utf8');
assert.match(pbx, /Bundle React Native code and images/);
assert.match(pbx, /export:embed/);
assert.match(pbx, /subhan_allah\.mp3/);
assert.match(pbx, /com\.kosaai\.salatiq\.ioslocal/);
const hash = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
assert.equal(hash('assets/audio/subhan_allah.mp3'), hash('سبحان الله (1).mp3'));
assert.match(pbx, /subhan_allah\.mp3 in Resources/);
assert.match(pbx, /path = "\.\.\/assets\/audio\/subhan_allah\.mp3"/);
assert(fs.existsSync(path.join(root, appFolder, 'SplashScreen.storyboard')));
assert(fs.existsSync(path.join(root, appFolder, 'Images.xcassets/AppIcon.appiconset/Contents.json')));
console.log('PASS: iPhone config, front-only capture/orientation, Core ML contract/resources, bundled MP3, icon/splash and Release JS build phase.');
console.log('Structural verification only: no Xcode compilation or Apple Core ML runtime executed by this script.');
